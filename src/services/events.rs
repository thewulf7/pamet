//! Append-only event log: source of truth (Constitution Principle I). T006, T033, T039.

use crate::error::{Error, Result};
use crate::storage::{Backend, Store};
use chrono::Utc;
use rusqlite::params;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Event {
    pub id: i64,
    pub occurred_at: String,
    pub event_type: String,
    pub payload_json: String,
    pub schema_version: i64,
}

const VALID_EVENT_TYPES: [&str; 12] = [
    "write_decision",
    "retrieval",
    "outcome_update",
    "review_resolution",
    "tombstone",
    "cluster_formed",
    "summary_created",
    "consolidation_run_started",
    "consolidation_run_finished",
    "eval_run_completed",
    "item_decayed",
    "hindsight_memory_migrated",
];

/// Append one event to the log. Fails closed on an unknown event_type or
/// payload that is not valid JSON (T039 — never partially apply).
pub fn append_event(store: &Store, event_type: &str, payload: &serde_json::Value) -> Result<i64> {
    if !VALID_EVENT_TYPES.contains(&event_type) {
        return Err(Error::MalformedEvent(format!(
            "unknown event_type '{event_type}'"
        )));
    }
    let payload_json = serde_json::to_string(payload)?;
    let now = Utc::now().to_rfc3339();
    match &store.backend {
        Backend::Sqlite(conn) => {
            conn.execute(
                "INSERT INTO events (occurred_at, event_type, payload_json, schema_version) VALUES (?1, ?2, ?3, 1)",
                params![now, event_type, payload_json],
            )?;
            Ok(conn.last_insert_rowid())
        }
        #[cfg(feature = "postgres-backend")]
        Backend::Postgres(pool) => {
            let mut conn = pool.get()?;
            let row = conn.query_one(
                "INSERT INTO events (occurred_at, event_type, payload_json, schema_version) \
                 VALUES ($1, $2, $3, 1) RETURNING id",
                &[&now, &event_type, &payload_json],
            )?;
            Ok(row.get::<_, i64>(0))
        }
    }
}

/// Append one event to the log at replay time, preserving the original id
/// (rebuild/migrate — Constitution Principle I: replay must reproduce the
/// exact same event ids so every later event's FK reference still
/// resolves). The SQLite backend's `INTEGER PRIMARY KEY AUTOINCREMENT`
/// always allows an explicit id; the Postgres backend's `events.id` column
/// uses `GENERATED BY DEFAULT AS IDENTITY` specifically so the same is true
/// there (not `GENERATED ALWAYS`, which would reject this).
pub fn append_event_with_id(
    store: &Store,
    id: i64,
    occurred_at: &str,
    event_type: &str,
    payload_json: &str,
    schema_version: i64,
) -> Result<()> {
    match &store.backend {
        Backend::Sqlite(conn) => {
            conn.execute(
                "INSERT INTO events (id, occurred_at, event_type, payload_json, schema_version) \
                 VALUES (?1, ?2, ?3, ?4, ?5)",
                params![id, occurred_at, event_type, payload_json, schema_version],
            )?;
        }
        #[cfg(feature = "postgres-backend")]
        Backend::Postgres(pool) => {
            let mut conn = pool.get()?;
            conn.execute(
                "INSERT INTO events (id, occurred_at, event_type, payload_json, schema_version) \
                 VALUES ($1, $2, $3, $4, $5)",
                &[
                    &id,
                    &occurred_at,
                    &event_type,
                    &payload_json,
                    &(schema_version as i32),
                ],
            )?;
        }
    }
    Ok(())
}

/// Replay-ordered export of the event log, optionally filtered by `since` (T033).
pub fn export_log(store: &Store, since: Option<&str>) -> Result<Vec<Event>> {
    match &store.backend {
        Backend::Sqlite(conn) => {
            let sql = match since {
                Some(_) => {
                    "SELECT id, occurred_at, event_type, payload_json, schema_version FROM events \
                     WHERE occurred_at >= ?1 ORDER BY id ASC"
                }
                None => {
                    "SELECT id, occurred_at, event_type, payload_json, schema_version FROM events \
                     ORDER BY id ASC"
                }
            };
            let mut stmt = conn.prepare(sql)?;
            let mapper = |row: &rusqlite::Row| -> rusqlite::Result<Event> {
                Ok(Event {
                    id: row.get(0)?,
                    occurred_at: row.get(1)?,
                    event_type: row.get(2)?,
                    payload_json: row.get(3)?,
                    schema_version: row.get(4)?,
                })
            };
            let iter = match since {
                Some(s) => stmt.query_map(params![s], mapper)?,
                None => stmt.query_map(params![], mapper)?,
            };
            let mut rows = Vec::new();
            for row in iter {
                rows.push(row?);
            }
            Ok(rows)
        }
        #[cfg(feature = "postgres-backend")]
        Backend::Postgres(pool) => {
            let mut conn = pool.get()?;
            let rows = match since {
                Some(s) => conn.query(
                    "SELECT id, occurred_at, event_type, payload_json, schema_version FROM events \
                     WHERE occurred_at >= $1 ORDER BY id ASC",
                    &[&s],
                )?,
                None => conn.query(
                    "SELECT id, occurred_at, event_type, payload_json, schema_version FROM events \
                     ORDER BY id ASC",
                    &[],
                )?,
            };
            Ok(rows
                .into_iter()
                .map(|row| Event {
                    id: row.get(0),
                    occurred_at: row.get(1),
                    event_type: row.get(2),
                    payload_json: row.get(3),
                    schema_version: row.get::<_, i32>(4) as i64,
                })
                .collect())
        }
    }
}
